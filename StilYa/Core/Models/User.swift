import Foundation

struct User: Identifiable, Codable {
    let id: String
    var displayName: String?
    var email: String?
    var profileImagePath: String? // Storage path: users/{userId}/profile_image.jpg
    var modelImagePath: String? // Storage path: users/{userId}/model_image.jpg (uploaded full-body photo)
    var isModelPhotoAIGenerated: Bool // true if model photo was generated by AI

    var gender: String? // "female", "male", "unspecified"
    var height: String? // "short", "medium", "tall"
    var bodyType: String? // "xs-s", "m", "l", "xl-xxl" (legacy: "slim", "average", "curvy")
    var closetColor: String? // "darkWood", "lightWood", "white", "black", "navy", "green", "pink"
    var ageRange: String? // "18-24", "25-34", "35-44", "45+"
    var stylePreferences: [String]? // ["casual", "streetwear", "minimal", ...]
    var shoppingPreference: [String]? // ["mass-market", "premium", "vintage"]
    var howDidYouHear: String? // "instagram", "tiktok", "friend", "appstore", "other"

    var isPro: Bool
    var subscriptionExpiryDate: Date?
    var credits: Int
    var purchasedCredits: Int
    var weeklyCreditsLastReset: Date
    var totalCreditsUsed: Int
    var weeklyCreditsUsed: Int
    var proCredits: Int
    var subscriptionPlan: String?
    var proCreditsCycleStart: Date?
    var hasPurchased: Bool
    var referralCode: String?
    var referredBy: String?
    var referralCount: Int
    var modelPhotoGenCount: Int          // AI model photo generation count
    var modelPhotoGenLastReset: Date?    // Pro weekly reset date
    var encryptionKey: String?             // Base64 encoded AES-256 key (cross-device sync)
    var deviceId: String?
    var lastTransactionId: String?      // Duplicate purchase koruması
    var lastTransactionDate: Date?
    var createdAt: Date
    var updatedAt: Date

    // MARK: - Computed Properties
    var hasProfileImage: Bool {
        profileImagePath != nil
    }

    var hasModelImage: Bool {
        modelImagePath != nil
    }

    var canGenerateModelPhoto: Bool {
        if isPro {
            if let lastReset = modelPhotoGenLastReset {
                let days = Calendar.current.dateComponents([.day], from: lastReset, to: Date()).day ?? 0
                if days >= 7 { return true }
            } else {
                return true
            }
            return modelPhotoGenCount < 3
        } else {
            return modelPhotoGenCount < 1
        }
    }

    var remainingModelPhotoGenerations: Int {
        if isPro {
            if let lastReset = modelPhotoGenLastReset {
                let days = Calendar.current.dateComponents([.day], from: lastReset, to: Date()).day ?? 0
                if days >= 7 { return 3 }
            } else {
                return 3
            }
            return max(0, 3 - modelPhotoGenCount)
        } else {
            return max(0, 1 - modelPhotoGenCount)
        }
    }

    var totalAvailableCredits: Int {
        if isPro {
            return max(0, proCredits) + max(0, purchasedCredits) + max(0, credits)
        }
        return max(0, credits) + max(0, purchasedCredits)
    }

    var canTryOn: Bool {
        totalAvailableCredits > 0
    }

    var remainingCredits: Int {
        totalAvailableCredits
    }

    var needsProCycleReset: Bool {
        guard isPro, let cycleStart = proCreditsCycleStart, let plan = subscriptionPlan else {
            return false
        }
        let daysInCycle = plan == "weekly" ? 7 : 30
        let daysSinceCycle = Calendar.current.dateComponents([.day], from: cycleStart, to: Date()).day ?? 0
        return daysSinceCycle >= daysInCycle
    }

    var proCreditsMax: Int {
        guard let plan = subscriptionPlan else { return 0 }
        return plan == "weekly" ? AppConstants.proWeeklyCredits : AppConstants.proMonthlyCredits
    }

    var isSubscriptionActive: Bool {
        guard let expiryDate = subscriptionExpiryDate else { return false }
        return expiryDate > Date()
    }

    var needsWeeklyReset: Bool {
        let calendar = Calendar.current
        let daysSinceReset = calendar.dateComponents([.day], from: weeklyCreditsLastReset, to: Date()).day ?? 0
        return daysSinceReset >= 7
    }

    // MARK: - Initialization
    init(
        id: String,
        displayName: String? = nil,
        email: String? = nil,
        profileImagePath: String? = nil,
        modelImagePath: String? = nil,
        isModelPhotoAIGenerated: Bool = false,
        gender: String? = nil,
        height: String? = nil,
        bodyType: String? = nil,
        closetColor: String? = nil,
        ageRange: String? = nil,
        stylePreferences: [String]? = nil,
        shoppingPreference: [String]? = nil,
        howDidYouHear: String? = nil,
        isPro: Bool = false,
        subscriptionExpiryDate: Date? = nil,
        credits: Int = AppConstants.freeWeeklyCredits,
        purchasedCredits: Int = 0,
        weeklyCreditsLastReset: Date = Date(),
        totalCreditsUsed: Int = 0,
        weeklyCreditsUsed: Int = 0,
        proCredits: Int = 0,
        subscriptionPlan: String? = nil,
        proCreditsCycleStart: Date? = nil,
        hasPurchased: Bool = false,
        referralCode: String? = nil,
        referredBy: String? = nil,
        referralCount: Int = 0,
        modelPhotoGenCount: Int = 0,
        modelPhotoGenLastReset: Date? = nil,
        encryptionKey: String? = nil,
        deviceId: String? = nil,
        lastTransactionId: String? = nil,
        lastTransactionDate: Date? = nil,
        createdAt: Date = Date(),
        updatedAt: Date = Date()
    ) {
        self.id = id
        self.displayName = displayName
        self.email = email
        self.profileImagePath = profileImagePath
        self.modelImagePath = modelImagePath
        self.isModelPhotoAIGenerated = isModelPhotoAIGenerated
        self.gender = gender
        self.height = height
        self.bodyType = bodyType
        self.closetColor = closetColor
        self.ageRange = ageRange
        self.stylePreferences = stylePreferences
        self.shoppingPreference = shoppingPreference
        self.howDidYouHear = howDidYouHear
        self.isPro = isPro
        self.subscriptionExpiryDate = subscriptionExpiryDate
        self.credits = credits
        self.purchasedCredits = purchasedCredits
        self.weeklyCreditsLastReset = weeklyCreditsLastReset
        self.totalCreditsUsed = totalCreditsUsed
        self.weeklyCreditsUsed = weeklyCreditsUsed
        self.proCredits = proCredits
        self.subscriptionPlan = subscriptionPlan
        self.proCreditsCycleStart = proCreditsCycleStart
        self.hasPurchased = hasPurchased
        self.referralCode = referralCode
        self.referredBy = referredBy
        self.referralCount = referralCount
        self.modelPhotoGenCount = modelPhotoGenCount
        self.modelPhotoGenLastReset = modelPhotoGenLastReset
        self.encryptionKey = encryptionKey
        self.deviceId = deviceId
        self.lastTransactionId = lastTransactionId
        self.lastTransactionDate = lastTransactionDate
        self.createdAt = createdAt
        self.updatedAt = updatedAt
    }

    // MARK: - Codable Keys
    enum CodingKeys: String, CodingKey {
        case id
        case displayName
        case email
        case profileImagePath
        case modelImagePath
        case isModelPhotoAIGenerated
        case gender
        case height
        case bodyType
        case closetColor
        case ageRange
        case stylePreferences
        case shoppingPreference
        case howDidYouHear
        case isPro
        case subscriptionExpiryDate
        case credits
        case purchasedCredits
        case weeklyCreditsLastReset
        case totalCreditsUsed
        case weeklyCreditsUsed
        case proCredits
        case subscriptionPlan
        case proCreditsCycleStart
        case hasPurchased
        case referralCode
        case referredBy
        case referralCount
        case modelPhotoGenCount
        case modelPhotoGenLastReset
        case encryptionKey
        case deviceId
        case lastTransactionId
        case lastTransactionDate
        case createdAt
        case updatedAt
    }

    // MARK: - Custom Decoding (backward compat with old users)
    init(from decoder: Decoder) throws {
        let container = try decoder.container(keyedBy: CodingKeys.self)
        id = try container.decode(String.self, forKey: .id)
        displayName = try container.decodeIfPresent(String.self, forKey: .displayName)
        email = try container.decodeIfPresent(String.self, forKey: .email)
        profileImagePath = try container.decodeIfPresent(String.self, forKey: .profileImagePath)
        modelImagePath = try container.decodeIfPresent(String.self, forKey: .modelImagePath)
        isModelPhotoAIGenerated = try container.decodeIfPresent(Bool.self, forKey: .isModelPhotoAIGenerated) ?? false
        gender = try container.decodeIfPresent(String.self, forKey: .gender)
        height = try container.decodeIfPresent(String.self, forKey: .height)
        bodyType = try container.decodeIfPresent(String.self, forKey: .bodyType)
        closetColor = try container.decodeIfPresent(String.self, forKey: .closetColor)
        ageRange = try container.decodeIfPresent(String.self, forKey: .ageRange)
        stylePreferences = try container.decodeIfPresent([String].self, forKey: .stylePreferences)
        shoppingPreference = try container.decodeIfPresent([String].self, forKey: .shoppingPreference)
        howDidYouHear = try container.decodeIfPresent(String.self, forKey: .howDidYouHear)
        isPro = try container.decodeIfPresent(Bool.self, forKey: .isPro) ?? false
        subscriptionExpiryDate = try container.decodeIfPresent(Date.self, forKey: .subscriptionExpiryDate)
        credits = try container.decodeIfPresent(Int.self, forKey: .credits) ?? AppConstants.freeWeeklyCredits
        purchasedCredits = try container.decodeIfPresent(Int.self, forKey: .purchasedCredits) ?? 0
        weeklyCreditsLastReset = try container.decodeIfPresent(Date.self, forKey: .weeklyCreditsLastReset) ?? Date()
        totalCreditsUsed = try container.decodeIfPresent(Int.self, forKey: .totalCreditsUsed) ?? 0
        weeklyCreditsUsed = try container.decodeIfPresent(Int.self, forKey: .weeklyCreditsUsed) ?? 0
        proCredits = try container.decodeIfPresent(Int.self, forKey: .proCredits) ?? 0
        subscriptionPlan = try container.decodeIfPresent(String.self, forKey: .subscriptionPlan)
        proCreditsCycleStart = try container.decodeIfPresent(Date.self, forKey: .proCreditsCycleStart)
        hasPurchased = try container.decodeIfPresent(Bool.self, forKey: .hasPurchased) ?? false
        referralCode = try container.decodeIfPresent(String.self, forKey: .referralCode)
        referredBy = try container.decodeIfPresent(String.self, forKey: .referredBy)
        referralCount = try container.decodeIfPresent(Int.self, forKey: .referralCount) ?? 0
        modelPhotoGenCount = try container.decodeIfPresent(Int.self, forKey: .modelPhotoGenCount) ?? 0
        modelPhotoGenLastReset = try container.decodeIfPresent(Date.self, forKey: .modelPhotoGenLastReset)
        encryptionKey = try container.decodeIfPresent(String.self, forKey: .encryptionKey)
        deviceId = try container.decodeIfPresent(String.self, forKey: .deviceId)
        lastTransactionId = try container.decodeIfPresent(String.self, forKey: .lastTransactionId)
        lastTransactionDate = try container.decodeIfPresent(Date.self, forKey: .lastTransactionDate)
        createdAt = try container.decodeIfPresent(Date.self, forKey: .createdAt) ?? Date()
        updatedAt = try container.decodeIfPresent(Date.self, forKey: .updatedAt) ?? Date()
    }
}
